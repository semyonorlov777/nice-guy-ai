export function buildAnalyzeUserPrompt(answers: FunnelAnswer[]): string {
  const lines: string[] = [];
  lines.push("ОТВЕТЫ ЧЕЛОВЕКА В ДИАГНОСТИЧЕСКОМ РАЗГОВОРЕ:");
  lines.push("");
  for (let i = 0; i < answers.length; i++) {
    const a = answers[i];
    lines.push(`— ${a.questionText}`);
    lines.push(`  → ${a.answerText}`);
    lines.push("");
  }
  lines.push("");
  lines.push("Напиши персональный разбор по правилам выше. 700–1000 слов. Markdown.");
  return lines.join("\n");
}
