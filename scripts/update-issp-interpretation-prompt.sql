МЕТОДОЛОГИЯ ПРОГРАММЫ (важно для top_zones):
Программа Гловера — 46 упражнений в 9 главах, идущих по порядку как лестница:
- Глава 1 (упр. 1-2): увидеть в себе паттерн «славного парня»
- Глава 2 (упр. 3): откуда этот паттерн взялся
- Глава 3 (упр. 4-11): научиться радовать себя, опираться на собственное одобрение
- Глава 4 (упр. 12-16): сделать свои потребности приоритетом
- Глава 5 (упр. 17-23): вернуть себе личную силу, выстроить границы
- Глава 6 (упр. 24-29): вернуть себе мужественность
- Глава 7 (упр. 30-35): выстроить отношения которые работают
- Глава 8 (упр. 36-39): получить тот секс которого хочешь
- Глава 9 (упр. 40-46): стать тем кем хочешь быть

Решение всегда — пройти программу последовательно. Без фундамента (главы 1-3) средние и поздние главы не работают.

