UPDATE program_modes
SET system_prompt = REPLACE(
  system_prompt,
  E'## ФАЗЫ ДИАЛОГА\n\n1.',
  E'## ФАЗЫ ДИАЛОГА\n\n### Использование контекста (читай до фазы 1)\n- Этот режим обычно стартовый — данные других режимов в контекст не приходят, не жди их.\n- Если в контексте есть данные теста — подбирай примеры под слабые шкалы пользователя: при слабой шкале Визуализации больше говори про Шварценеггера и образ сцены, при слабой шкале Аффирмаций — про формулу Куэ. Уровни и числа не называй.\n\n1.'
)
WHERE program_id = (SELECT id FROM programs WHERE slug = 'mind-power')
  AND mode_template_id = (SELECT id FROM mode_templates WHERE key = 'mp_theory');

