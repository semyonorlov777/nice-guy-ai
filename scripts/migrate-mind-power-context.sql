-- ---------------------------------------------------------------------------
-- Верификация
-- ---------------------------------------------------------------------------

SELECT
  mt.key,
  pm.welcome_mode_label,
  (pm.system_prompt LIKE '%### Использование контекста%') AS has_context_block,
  LENGTH(pm.system_prompt) AS sp_len
FROM program_modes pm
JOIN mode_templates mt ON mt.id = pm.mode_template_id
JOIN programs p ON p.id = pm.program_id
WHERE p.slug = 'mind-power'
  AND mt.key IN ('mp_theory','mp_belief_audit','mp_visualization','mp_affirmations','mp_imprinting','mp_victory_album','mp_problem_lab')
ORDER BY pm.sort_order;
